#!/usr/bin/env python3
"""Generate one Kustomize overlay per implementation, from the source tree.

The overlays used to be maintained by hand, and had drifted away from what is
in src/: `graalvm-rest-quarkus-native` existed with no source directory behind
it, while `graalvm/micronaut` and `graalvm/spring` had no overlay at all. An
overlay that does not correspond to an implementation deploys nothing; an
implementation without one is silently absent from every run.

Generating them makes the relationship 1:1 and checkable:

    python scripts/generate-overlays.py --check    # CI: fail if stale
    python scripts/generate-overlays.py            # rewrite

Naming is derived from the path, so it cannot drift:

    src/go/fiber              -> go-rest-fiber
    src/rust/grpc/tonic       -> rust-grpc-tonic
    src/python/graphql/ariadne-> python-graphql-ariadne
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
OVERLAYS = REPO / "deploy" / "k3s" / "overlays"

# Every implementation listens on 8080. That is part of the contract, not a
# per-implementation choice: the Service targets one port and the runner one
# URL. See docs/ACTION_PLAN.md, Fase 3.
CONTAINER_PORT = 8080

PROTOCOLS = ("grpc", "graphql")   # anything else under an environment is REST

# Directories under src/<env>/ that are not implementations.
NOT_AN_IMPL = {"k8s", "shared", "common", ".omc"}


def slug(text: str) -> str:
    return text.replace("_", "-").lower()


def discover() -> list[tuple[str, str, str, Path]]:
    """-> (protocol, environment, implementation, source dir)"""
    found: list[tuple[str, str, str, Path]] = []
    for env_dir in sorted(p for p in SRC.iterdir() if p.is_dir() and p.name not in NOT_AN_IMPL):
        for child in sorted(p for p in env_dir.iterdir() if p.is_dir()):
            if child.name in NOT_AN_IMPL:
                continue
            if child.name in PROTOCOLS:
                for impl in sorted(p for p in child.iterdir() if p.is_dir()):
                    if impl.name in NOT_AN_IMPL:
                        continue
                    found.append((child.name, env_dir.name, impl.name, impl))
            else:
                found.append(("rest", env_dir.name, child.name, child))
    return found


def is_implementation(path: Path) -> tuple[bool, str]:
    """An implementation needs something to build. A directory holding only
    k8s manifests is a leftover, not an implementation -- src/java/grpc/grpc-js
    is one, and it has been inflating the counts."""
    if (path / "Dockerfile").exists():
        return True, ""
    contents = {p.name for p in path.iterdir()}
    if contents <= {"k8s"}:
        return False, "only a k8s/ directory: no source, no Dockerfile"
    return False, "no Dockerfile"


KUSTOMIZATION = """# Generated by scripts/generate-overlays.py -- do not edit by hand.
# Source: {source}
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization

namespace: benchmark

resources:
  - ../../../base

commonLabels:
  app: {name}
  benchmark-protocol: {protocol}
  benchmark-environment: {environment}
  benchmark-framework: {framework}

patches:
  - target:
      kind: Deployment
      name: PLACEHOLDER
    patch: |-
      - op: replace
        path: /metadata/name
        value: {name}
      - op: replace
        path: /spec/selector/matchLabels/app
        value: {name}
      - op: replace
        path: /spec/template/metadata/labels/app
        value: {name}
      - op: replace
        path: /spec/template/spec/containers/0/image
        value: benchmark/{name}:latest
      - op: replace
        path: /spec/template/spec/containers/0/ports/0/containerPort
        value: {port}
      - op: replace
        path: /spec/template/spec/containers/0/envFrom/0/configMapRef/name
        value: {name}-config

  - target:
      kind: Service
      name: PLACEHOLDER
    patch: |-
      - op: replace
        path: /metadata/name
        value: {name}
      - op: replace
        path: /spec/selector/app
        value: {name}

  - target:
      kind: ConfigMap
      name: PLACEHOLDER-config
    patch: |-
      - op: replace
        path: /metadata/name
        value: {name}-config
      - op: replace
        path: /data/PORT
        value: "{port}"
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any overlay is missing, stale or orphaned")
    args = ap.parse_args()

    wanted: dict[str, str] = {}      # protocol/name -> rendered kustomization
    skipped: list[tuple[str, str]] = []

    for protocol, environment, framework, source in discover():
        ok, why = is_implementation(source)
        name = f"{slug(environment)}-{protocol}-{slug(framework)}"
        if not ok:
            skipped.append((name, why))
            continue
        wanted[f"{protocol}/{name}"] = KUSTOMIZATION.format(
            source=source.relative_to(REPO).as_posix(),
            name=name, protocol=protocol,
            environment=slug(environment), framework=slug(framework),
            port=CONTAINER_PORT,
        )

    existing = {
        f"{proto.name}/{ov.name}"
        for proto in OVERLAYS.iterdir() if proto.is_dir()
        for ov in proto.iterdir() if ov.is_dir()
    }

    missing = sorted(set(wanted) - existing)
    orphaned = sorted(existing - set(wanted))
    stale = sorted(
        key for key in set(wanted) & existing
        if (OVERLAYS / key / "kustomization.yaml").read_text(encoding="utf-8") != wanted[key]
    )

    for name, why in skipped:
        print(f"[skip] {name}: {why}")
    for key in missing:
        print(f"[missing]  {key}")
    for key in orphaned:
        print(f"[orphaned] {key} -- no implementation in src/")
    for key in stale:
        print(f"[stale]    {key}")

    if args.check:
        bad = len(missing) + len(orphaned) + len(stale)
        print(f"\n{len(wanted)} implementations, {bad} overlay problems")
        return 1 if bad else 0

    for key, body in wanted.items():
        target = OVERLAYS / key
        target.mkdir(parents=True, exist_ok=True)
        (target / "kustomization.yaml").write_text(body, encoding="utf-8")
    for key in orphaned:
        shutil.rmtree(OVERLAYS / key)
        print(f"[removed]  {key}")

    print(f"\n{len(wanted)} overlays written, {len(orphaned)} removed, "
          f"{len(skipped)} directories skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
