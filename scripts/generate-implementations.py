#!/usr/bin/env python3
"""Generate config/implementations.yaml from the source tree.

This file used to be maintained by hand and was the declared "source of truth",
but it had drifted away from reality: 99 entries against 100 overlays, 57 marked
maturity: planned (against implementations that physically exist), port 50051
for gRPC (the contract is 8080), and a `defaults` block declaring 1 CPU / 512 Mi
/ 5 replicas -- exactly the profile Fase 4 removed. Two sources of truth that
disagree is the same defect as the two deploy sources Fase 4 fixed.

Generating it from src/ makes it agree with the overlays by construction, since
both come from the same discovery walk. The YAML schema is preserved so the
naive line-by-line parsers in build-image.sh and list-implementations.sh keep
working:

    python scripts/generate-implementations.py          # rewrite
    python scripts/generate-implementations.py --check   # CI: fail if stale

`maturity` is not derivable from the tree, so every entry is emitted as
`maturity: stable` (the file exists; whether it builds is Fase 6's question,
not this file's). The previous experimental/planned/missing labels described
intent, not state, and intent that contradicts the tree is noise.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
CONFIG = REPO / "config" / "implementations.yaml"

# Same constants as generate-overlays.py -- the two must agree.
CONTAINER_PORT = 8080
PROTOCOLS = ("grpc", "graphql")
NOT_AN_IMPL = {"k8s", "shared", "common", ".omc"}

# Environment display order for stable, human-readable output.
ENV_ORDER = (
    "rust", "go", "csharp", "nodejs", "bun", "deno",
    "python", "dart", "java", "kotlin", "graalvm",
)


def slug(text: str) -> str:
    return text.replace("_", "-").lower()


def discover() -> list[tuple[str, str, str, Path]]:
    """-> [(protocol, environment, framework, source_dir)].

    Identical to generate-overlays.discover(). Duplicated rather than imported
    so this script has no dependency on the overlay generator (and vice versa);
    if they ever disagree, --check on both catches it.
    """
    found: list[tuple[str, str, str, Path]] = []
    for env_dir in sorted(p for p in SRC.iterdir() if p.is_dir() and p.name not in NOT_AN_IMPL):
        for child in sorted(p for p in env_dir.iterdir() if p.is_dir()):
            if child.name in NOT_AN_IMPL:
                continue
            if child.name in PROTOCOLS:
                for impl in sorted(p for p in child.iterdir() if p.is_dir()):
                    if impl.name in NOT_AN_IMPL:
                        continue
                    found.append((child.name, env_dir.name, impl.name, impl))
            else:
                found.append(("rest", env_dir.name, child.name, child))
    return found


def is_implementation(path: Path) -> tuple[bool, str]:
    """Same rule as generate-overlays: needs a buildable artifact."""
    if (path / "Dockerfile").exists():
        return True, ""
    contents = {p.name for p in path.iterdir()}
    if contents <= {"k8s"}:
        return False, "only a k8s/ directory: no source, no Dockerfile"
    return False, "no Dockerfile"


HEADER = """\
# config/implementations.yaml
#
# GENERATED by scripts/generate-implementations.py -- do not edit by hand.
# Source: src/ (same discovery walk as generate-overlays.py). If the two ever
# disagree, both --check gates fail.
#
# Each implementation has a unique ID: <environment>-<protocol>-<framework>
# Port is 8080 for all protocols (the contract); gRPC runs over HTTP/2 on the
# same port. `maturity: stable` here means "the source directory exists", not
# "builds and passes parity" -- that is Fase 6's E4 verdict, recorded in
# docs/BUILD_MATRIX.md, not in this file.
#
# There is intentionally no `defaults` block. Resource profile (7 CPU / 12 Gi,
# 1 replica, QoS Guaranteed) lives in deploy/k3s/base/deployment.yaml and is
# the only place it lives. The previous defaults (1 CPU / 512 Mi / 5 replicas)
# were the profile Fase 4 removed.

implementations:
"""


def render_entry(environment: str, protocol: str, framework: str, source: Path) -> str:
    impl_id = f"{slug(environment)}-{protocol}-{slug(framework)}"
    return (
        f"  - id: {impl_id}\n"
        f"    environment: {environment}\n"
        f"    protocol: {protocol}\n"
        f"    framework: {slug(framework)}\n"
        f"    path: {source.relative_to(REPO).as_posix()}\n"
        f"    port: {CONTAINER_PORT}\n"
        f"    maturity: stable\n"
    )


def render() -> tuple[str, list[tuple[str, str]]]:
    entries: list[tuple[str, str, str, Path]] = []
    skipped: list[tuple[str, str]] = []
    for protocol, environment, framework, source in discover():
        ok, why = is_implementation(source)
        if not ok:
            skipped.append((f"{slug(environment)}-{protocol}-{slug(framework)}", why))
            continue
        entries.append((environment, protocol, framework, source))

    # Group by environment (in canonical order), then protocol, for readability.
    env_index = {e: i for i, e in enumerate(ENV_ORDER)}
    entries.sort(key=lambda e: (env_index.get(e[0], 99), e[1], e[2]))

    out = [HEADER]
    last_env: str | None = None
    for environment, protocol, framework, source in entries:
        if environment != last_env:
            out.append(f"\n  # {'=' * 68}\n  # {environment.upper()}\n  # {'=' * 68}\n")
            last_env = environment
        out.append(render_entry(environment, protocol, framework, source))

    return "".join(out), skipped


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the file is stale vs src/")
    args = ap.parse_args()

    rendered, skipped = render()

    if args.check:
        existing = CONFIG.read_text(encoding="utf-8") if CONFIG.exists() else ""
        if existing == rendered:
            return 0
        print("config/implementations.yaml is stale. Regenerate with:")
        print("  python scripts/generate-implementations.py")
        return 1

    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    CONFIG.write_text(rendered, encoding="utf-8")
    count = rendered.count("  - id:")
    print(f"Wrote {CONFIG.relative_to(REPO)} ({count} implementations)")
    for name, why in skipped:
        print(f"[skip] {name}: {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
