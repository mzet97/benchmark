#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
PROTO_DIR="$PROJECT_ROOT/contracts/grpc"
IMAGE_NAME="benchmark-grpc-tonic"
IMAGE_TAG="${1:-latest}"

echo "=== Building Rust tonic gRPC server ==="

# Generate proto code (done automatically by build.rs during cargo build)
echo "Proto code will be generated by tonic-build during cargo build"

# Build Docker image
echo "Building Docker image: $IMAGE_NAME:$IMAGE_TAG"
docker build \
  -f "$SCRIPT_DIR/Dockerfile" \
  -t "$IMAGE_NAME:$IMAGE_TAG" \
  "$PROJECT_ROOT"

echo "=== Build complete: $IMAGE_NAME:$IMAGE_TAG ==="
